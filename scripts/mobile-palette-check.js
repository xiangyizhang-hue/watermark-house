(async () => {
  const panel = document.querySelector('.photo-palette')
  if (!panel) throw Error('Open magazine information panel on the PNG regression photo')
  const read = () => [...panel.querySelectorAll('input[type=color]')].map(e=>e.value)
  panel.querySelector('button').click()
  await new Promise(r=>setTimeout(r,100))
  for (let i=0;i<100 && (panel.querySelector('button').disabled || !read().length);i++) await new Promise(r=>setTimeout(r,100))
  const initial = read()
  if (initial.length !== Number(panel.querySelector('select').value)) throw Error(panel.innerText)
  const select = panel.querySelector('select'); select.value='3'; select.dispatchEvent(new Event('change',{bubbles:true}))
  for (let i=0;i<100 && read().length!==3;i++) await new Promise(r=>setTimeout(r,100))
  const three = read()
  if (three.length!==3) throw Error('Palette count did not update')
  const color = panel.querySelector('input[type=color]'); color.value='#123456'; color.dispatchEvent(new Event('input',{bubbles:true}))
  await new Promise(r=>setTimeout(r,100))
  if (read()[0]!=='#123456') throw Error('Manual color edit failed')
  panel.querySelector('button').click()
  await new Promise(r=>setTimeout(r,100))
  for (let i=0;i<100 && panel.querySelector('button').disabled;i++) await new Promise(r=>setTimeout(r,100))
  const reset = read()
  if (JSON.stringify(reset)!==JSON.stringify(three)) throw Error('Fresh extraction differs from automatic original colors')
  return {initial,three,reset,passed:true}
})()
